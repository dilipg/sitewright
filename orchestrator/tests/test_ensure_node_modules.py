"""X1: a stale `node_modules` link must be repaired, not crash the run.

`ensure_node_modules` branched on `Path.exists()`, which FOLLOWS a link — so a
dangling link looked identical to no link, and the code then tried to CREATE one
where a path already existed. `mklink` refuses that, so a broken link raised
instead of self-healing. A container-built project opened on the host is exactly
that state.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from orchestrator.design_pipeline import ensure_node_modules
from orchestrator.portable import link_directory


def test_links_a_project_that_has_none(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    fixture = _fake_fixture(tmp_path, monkeypatch)
    project = tmp_path / "project"
    project.mkdir()

    ensure_node_modules(project)

    # Asserts RESOLUTION, not `is_symlink()`: on Windows a junction reports
    # is_symlink() == False (measured), so asserting it would fail on correct
    # code here and pass only on POSIX. What the preview child needs is that
    # an import resolves through the link.
    assert (project / "node_modules" / "marker.txt").exists()
    assert fixture.exists()


def test_repairs_a_dangling_link_instead_of_raising(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _fake_fixture(tmp_path, monkeypatch)
    project = tmp_path / "project"
    project.mkdir()
    # The measured X1 state: a link to a layout that does not exist here.
    link_directory(project / "node_modules", tmp_path / "app" / "fixtures" / "node_modules")
    assert not (project / "node_modules").exists()  # premise: genuinely broken

    ensure_node_modules(project)

    assert (project / "node_modules" / "marker.txt").exists()


def test_leaves_a_healthy_link_alone(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    fixture = _fake_fixture(tmp_path, monkeypatch)
    project = tmp_path / "project"
    project.mkdir()
    link_directory(project / "node_modules", fixture)

    ensure_node_modules(project)

    assert (project / "node_modules" / "marker.txt").exists()


def test_never_replaces_a_real_node_modules_directory(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A project that owns its dependencies keeps them."""
    _fake_fixture(tmp_path, monkeypatch)
    project = tmp_path / "project"
    (project / "node_modules" / "installed-here").mkdir(parents=True)

    ensure_node_modules(project)

    assert (project / "node_modules" / "installed-here").exists()
    # Still a real directory, not swapped for a link. `lexists` and `exists`
    # agree for a real directory, which is what kept it out of the repair.
    assert (project / "node_modules" / "installed-here").is_dir()


def test_is_idempotent(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    _fake_fixture(tmp_path, monkeypatch)
    project = tmp_path / "project"
    project.mkdir()
    link_directory(project / "node_modules", tmp_path / "gone")

    ensure_node_modules(project)
    ensure_node_modules(project)

    assert (project / "node_modules" / "marker.txt").exists()


def _fake_fixture(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A stand-in fixture dir, so these never touch the real one."""
    fixture_root = tmp_path / "fixtures" / "acme-landing"
    node_modules = fixture_root / "node_modules"
    node_modules.mkdir(parents=True)
    (node_modules / "marker.txt").write_text("borrowed", encoding="utf-8")
    monkeypatch.setattr("orchestrator.fixture_context.FIXTURE_DIR", fixture_root)
    return node_modules
